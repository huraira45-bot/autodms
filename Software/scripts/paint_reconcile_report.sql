-- Attach best-match paint_Item.
IF OBJECT_ID('tempdb..#matched') IS NOT NULL DROP TABLE #matched;
SELECT
    x.Code, x.ItemNo, x.Name AS XlsxName, x.Qty AS XlsxQty, x.Rate AS XlsxRate, x.UnitSize,
    pByCode.PaintItemID AS ByCodeID, pByCode.PaintName AS ByCodeName,
    pByName.PaintItemID AS ByNameID, pByName.PaintName AS ByName,
    COALESCE(pByCode.PaintItemID, pByName.PaintItemID) AS MatchedID
INTO #matched
FROM #xlsx x
LEFT JOIN paint_Item pByCode ON pByCode.PaintCode = CAST(x.Code AS NVARCHAR(50))
LEFT JOIN paint_Item pByName ON pByCode.PaintItemID IS NULL
                             AND UPPER(LTRIM(RTRIM(pByName.PaintName))) = UPPER(LTRIM(RTRIM(x.Name)));

PRINT '========== A. MATCHED — qty or rate differs ==========';
SELECT
    m.MatchedID, m.Code, m.XlsxName AS Name,
    pi.PaintName AS DB_Name,
    pi.StockQty AS DB_Qty, m.XlsxQty AS Xlsx_Qty, (m.XlsxQty - pi.StockQty) AS QtyDelta,
    pi.AvgCost AS DB_Rate, m.XlsxRate AS Xlsx_Rate, (m.XlsxRate - pi.AvgCost) AS RateDelta,
    m.UnitSize
FROM #matched m
INNER JOIN paint_Item pi ON pi.PaintItemID = m.MatchedID
WHERE ABS(pi.StockQty - m.XlsxQty) > 0.01 OR ABS(pi.AvgCost - m.XlsxRate) > 0.01
ORDER BY m.XlsxName;

PRINT '========== B. NEW — in xlsx, not in DB ==========';
SELECT m.Code, m.XlsxName AS Name, m.ItemNo, m.XlsxQty, m.XlsxRate, m.UnitSize
FROM #matched m
WHERE m.MatchedID IS NULL
ORDER BY m.XlsxName;

