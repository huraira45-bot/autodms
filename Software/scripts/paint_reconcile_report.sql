SELECT
    pi.PaintItemID, pi.PaintCode, pi.PaintName, pi.StockQty, pi.AvgCost, pi.IsActive,
    (SELECT COUNT(*) FROM paint_StockLedger sl WHERE sl.PaintItemID = pi.PaintItemID) AS LedgerRows,
